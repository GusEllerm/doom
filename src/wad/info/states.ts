/** states[i] as a row object. Out-of-range indexes throw (typed upgrade of
 *  vanilla's silent OOB read; pinned by states.test.ts). */
export function stateAt(i: number): StateRow {
  if (!Number.isInteger(i) || i < 0 || i >= NUMSTATES) {
    throw new RangeError(`stateAt: state id ${i} outside 0..${NUMSTATES - 1}`)
  }
  return {
    id: i,
    sprite: stateSprite[i] as number,
    frame: stateFrame[i] as number,
    tics: stateTics[i] as number,
    action: stateAction[i] as number,
    nextstate: stateNext[i] as number,
    misc1: stateMisc1[i] as number,
    misc2: stateMisc2[i] as number,
  }
}

/** One visited state inside a P_SetMobjState cascade (action-on-entry order). */
export interface ChainStep {
  state: number
  action: number
  /** table tics at entry, BEFORE any action modification (informational) */
  tics: number
}

export interface ChainResult {
  /** false ⇒ S_NULL reached ⇒ object removed (P_SetMobjState returns false) */
  alive: boolean
  /** final state id (0 when !alive) */
  state: number
  /** table tics of the final state (before action modification) */
  tics: number
  /** every state entered during the call, in execution order */
  steps: ChainStep[]
}

/** Iteration cap for the 0-tic cascade loop. Vanilla has NO guard — a
 *  table/action combo that never lands on tics!=0 or S_NULL hangs the game;
 *  the table alone cannot do it (checked exhaustively below), so the cap only
 *  fires if a registered action keeps returning tics=0 forever. Documented
 *  deviation (test-pinned); vanilla would hang instead. */
export const MAX_STATE_CHAIN = 1024

/**
 * Pure-data transcription of P_SetMobjState's do/while loop (R06 §1,
 * p_mobj.c:48-86) — the 0-tic cascade rules an mobj runtime must follow:
 *   state==S_NULL ⇒ removed; else enter state, run its action (callback may
 *   override tics — vanilla actions mutate mobj->tics, e.g. A_WeaponReady
 *   does NOT, randomizing actions do), loop while tics===0.
 * Action EXECUTION is deferred to the callers (M7-02+ bind ActionId → body);
 * the callback contract here keeps the ADVANCE ORDER testable now.
 */
export function setStateChain(
  start: number,
  onAction?: (state: number, action: number) => number | void,
): ChainResult {
  const steps: ChainStep[] = []
  let state = start
  for (;;) {
    if (steps.length >= MAX_STATE_CHAIN) {
      throw new Error(`setStateChain: 0-tic cascade exceeded ${MAX_STATE_CHAIN} states (vanilla would hang)`)
    }
    if (state === S.S_NULL) {
      return { alive: false, state: S.S_NULL, tics: 0, steps }
    }
    const row = stateAt(state)
    steps.push({ state, action: row.action, tics: row.tics })
    let tics = row.tics
    if (onAction !== undefined && row.action !== 0) {
      const override = onAction(state, row.action)
      if (typeof override === 'number') tics = override
    }
    if (tics !== 0) return { alive: true, state, tics, steps }
    state = row.nextstate
  }
}

/**
 * stateAt(state, tic) — the visible state `tic` tics AFTER `state` was set,
 * pure-table semantics (no action side effects): resolve the set-time
 * cascade, then per P_MobjThinker (R06 §1): tics -1 never advances;
 * otherwise one decrement per tic and, on reaching 0, the nextstate cascade
 * (0-tic chains execute fully inside that tic).
 */
export function stateAdvance(start: number, tic: number): StateRow {
  if (!Number.isInteger(tic) || tic < 0) {
    throw new RangeError(`stateAdvance: tic ${tic} must be a non-negative integer`)
  }
  const chain = setStateChain(start)
  let state = chain.state
  let tics = chain.tics
  if (!chain.alive) return stateAt(S.S_NULL)
  for (let t = 0; t < tic; t++) {
    if (tics === -1) break
    tics--
    if (tics === 0) {
      const next = setStateChain(stateNext[state] as number)
      if (!next.alive) return stateAt(S.S_NULL)
      state = next.state
      tics = next.tics
      if (tics === -1) { /* stays */ }
    }
  }
  return stateAt(state)
}

/** Census helper: does the PURE table alone terminate every 0-tic chain?
 *  (Used by states.test.ts; returns worst chain length seen.) */
export function maxPureChainLength(): number {
  let worst = 0
  for (let i = 0; i < NUMSTATES; i++) {
    const r = setStateChain(i)
    if (r.steps.length > worst) worst = r.steps.length
  }
  return worst
}
